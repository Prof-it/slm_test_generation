# Data Classes
@dataclass
class AssertionClassification:
    """Result of assertion quality classification."""
    is_meaningful: bool
    reason: str
    assertion_count: int
    meaningful_count: int
    trivial_count: int
    meaningful_examples: List[str] = field(default_factory=list)
    trivial_examples: List[str] = field(default_factory=list)


@dataclass
class ComparisonCase:
    """A single comparison between Pynguin and SLM test."""
    dataset: str
    run: str
    model: str
    temperature: str
    task_num: str
    task_title: str
    target_line: str
    pynguin_status: str
    slm_status: str
    pynguin_classification: AssertionClassification
    slm_classification: AssertionClassification
    pynguin_test_sample: str
    slm_test_sample: str


@dataclass
class AnalysisResults:
    """Complete analysis results."""
    total_comparisons: int = 0
    unique_tasks: int = 0

    # Pass/Fail breakdown
    both_pass: int = 0
    both_fail: int = 0
    pynguin_fail_slm_pass: int = 0
    pynguin_pass_slm_fail: int = 0

    # Hypothesis test results (within pynguin_pass_slm_fail)
    supports_hypothesis: int = 0
    counter_examples: int = 0
    both_meaningful: int = 0
    both_trivial: int = 0

    # Task-level aggregation
    tasks_supporting: int = 0
    tasks_counter: int = 0

    # Example cases
    supporting_examples: List[Dict] = field(default_factory=list)
    counter_examples_list: List[Dict] = field(default_factory=list)

    @property
    def support_ratio(self) -> Optional[float]:
        """Calculate the hypothesis support ratio."""
        total = self.supports_hypothesis + self.counter_examples
        if total > 0:
            return self.supports_hypothesis / total
        return None


# Utility Functions
def load_jsonl(filepath: Path) -> List[Dict]:
    """Load a JSONL file, returning list of parsed JSON objects."""
    if not filepath.exists():
        return []

    data = []
    with open(filepath, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if line:
                try:
                    data.append(json.loads(line))
                except json.JSONDecodeError as e:
                    print(f"Warning: Failed to parse line {line_num} in {filepath}: {e}")
                    continue
    return data


def clean_markdown(text: str) -> str:
    """Remove markdown code block markers from text."""
    if not text:
        return text

    # Remove ```python and ``` markers
    text = re.sub(r'```python\s*\n?', '', text)
    text = re.sub(r'```\s*\n?', '', text)
    # Remove single backticks around inline code
    text = re.sub(r'`([^`]+)`', r'\1', text)

    return text.strip()


def get_test_code(prediction: Dict, target_line: str = None) -> str:
    """Extract test code from a prediction record."""
    tests = prediction.get('tests', {})
    if not tests:
        return ''

    # If target_line specified, get that specific test
    if target_line and str(target_line) in tests:
        test_data = tests[str(target_line)]
        if isinstance(test_data, dict):
            return test_data.get('test_code', '')

    # Otherwise, combine all tests
    all_tests = []
    for key, test_data in tests.items():
        if isinstance(test_data, dict) and 'test_code' in test_data:
            all_tests.append(test_data['test_code'])

    return '\n'.join(all_tests)


# The CORE of the Script: Assertion Classification
# Patterns indicating MEANINGFUL assertions (algorithm-specific checks)
MEANINGFUL_PATTERNS = [
    # List comparisons with actual values
    (r'==\s*\[\s*[\d\-\[\],\s]+\s*\]', 'list with numbers'),
    (r'==\s*\[\s*\[', 'nested list'),

    # Function result compared to number (including 0)
    (r'\)\s*==\s*-?\d+\.?\d*', 'function result equals number'),
    (r'==\s*-?[1-9]\d*\.?\d*', 'specific non-zero number'),

    # String comparisons (non-empty)
    (r'==\s*["\'][^"\']+["\']', 'specific string'),

    # pytest.approx comparisons
    (r'pytest\.approx\s*\(\s*-?\d', 'pytest.approx with value'),

    # Epsilon comparisons for floating point
    (r'abs\s*\(.+\)\s*<', 'epsilon comparison'),

    # Solution method calls with expected output
    (r'solution\.\w+\s*\(.+\)\s*==', 'solution method with expected'),
]

# Patterns indicating TRIVIAL assertions (don't verify algorithm correctness)
TRIVIAL_PATTERNS = [
    (r'assert\s+True\s*$', 'assert True'),
    (r'assert\s+False\s*$', 'assert False'),
    (r'is\s+not\s+None', 'is not None check'),
    (r'is\s+None\s*$', 'is None check'),
    (r'isinstance\s*\(', 'isinstance check'),
    (r'==\s*\[\s*\]\s*$', 'empty list comparison'),
    (r'==\s*\{\s*\}\s*$', 'empty dict comparison'),
    (r'==\s*["\']["\']', 'empty string comparison'),
    (r'==\s*None\s*$', 'equals None'),
    (r'assert\s+\w+\s*$', 'bare variable assertion'),
]


def extract_assertions(test_code: str) -> List[str]:
    """Extract all assertion statements from test code, handling multi-line assertions."""
    assertions = []

    # Pattern to match assertions that may span multiple lines
    # Matches 'assert' followed by content until newline+non-whitespace or end
    assertion_pattern = r'assert\s+.+?(?=\n(?!\s)|$)'
    matches = re.findall(assertion_pattern, test_code, re.DOTALL)

    for match in matches:
        # Normalize whitespace for analysis
        normalized = ' '.join(match.split())
        assertions.append(normalized)

    # Also check for unittest-style assertions
    unittest_pattern = r'self\.assert\w+\s*\([^)]+\)'
    unittest_matches = re.findall(unittest_pattern, test_code)
    assertions.extend(unittest_matches)

    return assertions


def classify_assertion_quality(test_code: str) -> AssertionClassification:
    """
    Classify the quality of assertions in test code.

    Classification is based on assertion CONTENT, applying the same rules
    to both Pynguin and SLM generated tests for unbiased comparison.

    Args:
        test_code: The test code to analyze

    Returns:
        AssertionClassification with detailed results
    """
    if not test_code:
        return AssertionClassification(
            is_meaningful=False,
            reason='No test code',
            assertion_count=0,
            meaningful_count=0,
            trivial_count=0
        )

    # Clean markdown formatting
    test_code = clean_markdown(test_code)

    # Check for assertion presence
    if 'assert' not in test_code.lower():
        return AssertionClassification(
            is_meaningful=False,
            reason='No assertions',
            assertion_count=0,
            meaningful_count=0,
            trivial_count=0
        )

    # Extract assertions
    assertions = extract_assertions(test_code)

    if not assertions:
        # Check for pytest.approx in whole code as fallback
        if 'pytest.approx' in test_code:
            assertions = ['pytest.approx found']
        else:
            return AssertionClassification(
                is_meaningful=False,
                reason='No assertion statements found',
                assertion_count=0,
                meaningful_count=0,
                trivial_count=0
            )

    # Classify each assertion
    meaningful_count = 0
    trivial_count = 0
    meaningful_examples = []
    trivial_examples = []

    for assertion in assertions:
        is_meaningful = False
        is_trivial = False

        # Check meaningful patterns first
        for pattern, desc in MEANINGFUL_PATTERNS:
            if re.search(pattern, assertion, re.IGNORECASE):
                meaningful_count += 1
                is_meaningful = True
                if len(meaningful_examples) < 3:
                    meaningful_examples.append(f"{desc}: {assertion[:80]}")
                break

        # If not meaningful, check trivial patterns
        if not is_meaningful:
            for pattern, desc in TRIVIAL_PATTERNS:
                if re.search(pattern, assertion, re.IGNORECASE):
                    trivial_count += 1
                    is_trivial = True
                    if len(trivial_examples) < 3:
                        trivial_examples.append(f"{desc}: {assertion[:80]}")
                    break

        # If no pattern matched but has comparison, count as potentially meaningful
        if not is_meaningful and not is_trivial:
            if '==' in assertion:
                meaningful_count += 1
                if len(meaningful_examples) < 3:
                    meaningful_examples.append(f"comparison: {assertion[:80]}")
            else:
                trivial_count += 1

    # Determine overall classification
    is_meaningful = meaningful_count > 0 and meaningful_count >= trivial_count

    if is_meaningful:
        reason = f'Meaningful ({meaningful_count} specific, {trivial_count} trivial)'
    elif trivial_count > 0:
        reason = f'Trivial ({trivial_count} trivial, {meaningful_count} specific)'
    else:
        reason = 'Unclear assertions'

    return AssertionClassification(
        is_meaningful=is_meaningful,
        reason=reason,
        assertion_count=len(assertions),
        meaningful_count=meaningful_count,
        trivial_count=trivial_count,
        meaningful_examples=meaningful_examples,
        trivial_examples=trivial_examples
    )


# Analysis Engine
def run_analysis(base_dir: Path) -> AnalysisResults:
    """
    Run the complete assertion quality analysis.

    Args:
        base_dir: Base directory of the benchmark repository

    Returns:
        AnalysisResults with all statistics and examples
    """
    results = AnalysisResults()
    unique_tasks = set()
    task_results = defaultdict(lambda: {'supports': 0, 'counter': 0})

    for dataset_config in DATASET_CONFIGS:
        ds_runs = dataset_config["runs"]
        ds_models = dataset_config["models"]
        ds_temps = dataset_config["temperatures"]

        for run in ds_runs:
            pred_path = base_dir / dataset_config["predictions"] / run
            eval_path = base_dir / dataset_config["evaluations"] / run

            if not pred_path.exists() or not eval_path.exists():
                continue

            # Load Pynguin data
            pynguin_preds = {
                str(p['task_num']): p
                for p in load_jsonl(pred_path / 'pynguin_results.jsonl')
            }
            pynguin_evals = {
                str(e['task_num']): e
                for e in load_jsonl(eval_path / 'pynguin_results_evaluated.jsonl')
            }

            # Pre-classify Pynguin assertions once per (run, task) — avoids redundant regex work
            pynguin_classifications = {}
            for task_num, pred in pynguin_preds.items():
                pynguin_test = get_test_code(pred)
                pynguin_classifications[task_num] = (pynguin_test, classify_assertion_quality(pynguin_test))

            # Process each SLM configuration
            for model in ds_models:
                for temp in ds_temps:
                    for prefix in PREFIXES:
                        slm_pred_file = pred_path / f'{prefix}_{model}_temp_{temp}.jsonl'
                        slm_eval_file = eval_path / f'{prefix}_{model}_temp_{temp}_evaluated.jsonl'

                        if not slm_pred_file.exists():
                            continue

                        slm_preds = {
                            str(p['task_num']): p
                            for p in load_jsonl(slm_pred_file)
                        }
                        slm_evals = load_jsonl(slm_eval_file)

                        for slm_eval in slm_evals:
                            task_num = str(slm_eval.get('task_num', ''))
                            target_line = str(slm_eval.get('target_line', ''))
                            slm_status = slm_eval.get('status', '')

                            # Skip if no matching Pynguin data
                            if task_num not in pynguin_preds:
                                continue

                            pynguin_pred = pynguin_preds[task_num]
                            pynguin_eval = pynguin_evals.get(task_num, {})
                            pynguin_status = pynguin_pred.get(
                                'status',
                                pynguin_eval.get('status', '')
                            )

                            if not pynguin_status:
                                continue

                            slm_pred = slm_preds.get(task_num, {})

                            # Get and classify test code (Pynguin cached, SLM per-comparison)
                            pynguin_test, pynguin_class = pynguin_classifications.get(
                                task_num, ("", classify_assertion_quality("")))
                            slm_test = get_test_code(slm_pred, target_line)
                            slm_class = classify_assertion_quality(slm_test)

                            pynguin_pass = pynguin_status == 'Pass'
                            slm_pass = slm_status == 'Pass'

                            # Update counts
                            results.total_comparisons += 1
                            unique_tasks.add(task_num)

                            # Categorize by pass/fail
                            if pynguin_pass and slm_pass:
                                results.both_pass += 1
                            elif not pynguin_pass and not slm_pass:
                                results.both_fail += 1
                            elif not pynguin_pass and slm_pass:
                                results.pynguin_fail_slm_pass += 1
                            elif pynguin_pass and not slm_pass:
                                results.pynguin_pass_slm_fail += 1

                                # This is our hypothesis test case
                                case_data = {
                                    "dataset": dataset_config["name"],
                                    "run": run,
                                    "model": model,
                                    "temperature": temp,
                                    "task_num": task_num,
                                    "task_title": pynguin_pred.get('task_title', ''),
                                    "target_line": target_line,
                                    "pynguin_status": pynguin_status,
                                    "slm_status": slm_status,
                                    "pynguin_meaningful": pynguin_class.is_meaningful,
                                    "slm_meaningful": slm_class.is_meaningful,
                                    "pynguin_reason": pynguin_class.reason,
                                    "slm_reason": slm_class.reason,
                                    "pynguin_test": pynguin_test[:600],
                                    "slm_test": slm_test[:600],
                                }

                                if not pynguin_class.is_meaningful and slm_class.is_meaningful:
                                    results.supports_hypothesis += 1
                                    task_results[task_num]['supports'] += 1
                                    if len(results.supporting_examples) < 20:
                                        results.supporting_examples.append(case_data)

                                elif pynguin_class.is_meaningful and not slm_class.is_meaningful:
                                    results.counter_examples += 1
                                    task_results[task_num]['counter'] += 1
                                    if len(results.counter_examples_list) < 20:
                                        results.counter_examples_list.append(case_data)

                                elif pynguin_class.is_meaningful and slm_class.is_meaningful:
                                    results.both_meaningful += 1
                                else:
                                    results.both_trivial += 1

    # Finalize results
    results.unique_tasks = len(unique_tasks)
    results.tasks_supporting = sum(
        1 for r in task_results.values() if r['supports'] > r['counter']
    )
    results.tasks_counter = sum(
        1 for r in task_results.values() if r['counter'] > r['supports']
    )

    return results


# Reporting
def generate_report(results: AnalysisResults) -> str:
    """Generate a formatted text report of the analysis results."""
    lines = []

    lines.append("=" * 80)
    lines.append("ASSERTION QUALITY ANALYSIS: PYNGUIN VS SLM")
    lines.append("=" * 80)
    lines.append("")
    lines.append("HYPOTHESIS:")
    lines.append("  Pynguin tests may pass with trivial assertions that don't verify")
    lines.append("  algorithm correctness, while SLM tests may fail but contain")
    lines.append("  meaningful assertions that test actual algorithm behavior.")
    lines.append("")

    lines.append("=" * 80)
    lines.append("DATA SUMMARY")
    lines.append("=" * 80)
    lines.append(f"Total comparisons: {results.total_comparisons:,}")
    lines.append(f"Unique tasks: {results.unique_tasks}")
    lines.append(f"Avg comparisons per task: {results.total_comparisons/max(results.unique_tasks,1):.1f}")
    lines.append("")

    lines.append("=" * 80)
    lines.append("PASS/FAIL BREAKDOWN")
    lines.append("=" * 80)
    total = results.total_comparisons
    lines.append(f"  Both pass:              {results.both_pass:5,} ({100*results.both_pass/total:.1f}%)")
    lines.append(f"  Both fail:              {results.both_fail:5,} ({100*results.both_fail/total:.1f}%)")
    lines.append(f"  Pynguin fail, SLM pass: {results.pynguin_fail_slm_pass:5,} ({100*results.pynguin_fail_slm_pass/total:.1f}%)")
    lines.append(f"  Pynguin pass, SLM fail: {results.pynguin_pass_slm_fail:5,} ({100*results.pynguin_pass_slm_fail/total:.1f}%)")
    lines.append("")

    lines.append("=" * 80)
    lines.append("HYPOTHESIS TEST: Pynguin Pass + SLM Fail Cases")
    lines.append("=" * 80)
    focus = results.pynguin_pass_slm_fail
    lines.append(f"Total cases: {focus:,}")
    lines.append("")
    lines.append(f"  SUPPORTS hypothesis (Pynguin trivial, SLM meaningful): {results.supports_hypothesis:5,} ({100*results.supports_hypothesis/focus:.1f}%)")
    lines.append(f"  COUNTER-EXAMPLES (Pynguin meaningful, SLM trivial):    {results.counter_examples:5,} ({100*results.counter_examples/focus:.1f}%)")
    lines.append(f"  Both meaningful (neutral):                             {results.both_meaningful:5,} ({100*results.both_meaningful/focus:.1f}%)")
    lines.append(f"  Both trivial (neutral):                                {results.both_trivial:5,} ({100*results.both_trivial/focus:.1f}%)")
    lines.append("")

    if results.support_ratio is not None:
        lines.append(f"Support ratio: {results.support_ratio:.1%}")
        lines.append(f"  ({results.supports_hypothesis:,} supporting vs {results.counter_examples:,} counter-examples)")
    lines.append("")

    lines.append("=" * 80)
    lines.append("TASK-LEVEL ANALYSIS")
    lines.append("=" * 80)
    lines.append(f"Tasks where hypothesis supported: {results.tasks_supporting}")
    lines.append(f"Tasks where counter-examples dominate: {results.tasks_counter}")
    lines.append("")

    lines.append("=" * 80)
    lines.append("CONCLUSION")
    lines.append("=" * 80)

    if results.support_ratio is not None:
        if results.support_ratio > 0.6:
            lines.append("The hypothesis is SUPPORTED.")
        elif results.support_ratio < 0.4:
            lines.append("The hypothesis is REFUTED.")
        else:
            lines.append("The evidence is INCONCLUSIVE.")

        lines.append("")
        lines.append(f"In {results.support_ratio:.0%} of discriminating cases, Pynguin had trivial")
        lines.append("assertions while SLM had meaningful ones.")
        lines.append("")
        lines.append(f"Note: {100*results.both_meaningful/focus:.0f}% of cases had both meaningful assertions,")
        lines.append(f"      and {100*results.both_trivial/focus:.0f}% had both trivial assertions.")

    return "\n".join(lines)


