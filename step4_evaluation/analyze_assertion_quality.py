def main():
    """Main entry point for the analysis."""
    parser = argparse.ArgumentParser(
        description='Analyze assertion quality in Pynguin vs SLM generated tests'
    )
    parser.add_argument(
        '--base-dir',
        type=Path,
        default=DEFAULT_BASE_DIR,
        help='Base directory of the benchmark repository'
    )
    parser.add_argument(
        '--output-dir',
        type=Path,
        default=None,
        help='Directory for output files (default: base_dir/step4_evaluation)'
    )

    args = parser.parse_args()

    output_dir = args.output_dir or (args.base_dir / 'step4_evaluation')
    output_dir.mkdir(parents=True, exist_ok=True)

    print("Running assertion quality analysis...")
    print(f"Base directory: {args.base_dir}")
    print()

    # Run analysis
    results = run_analysis(args.base_dir)

    # Generate and print report
    report = generate_report(results)
    print(report)

    # Generate summary
    summary = generate_summary(results)

    # Save outputs
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    # Save JSON results
    json_output = output_dir / f'assertion_quality_results.json'
    with open(json_output, 'w', encoding='utf-8') as f:
        json.dump({
            'timestamp': timestamp,
            'stats': {
                'total_comparisons': results.total_comparisons,
                'unique_tasks': results.unique_tasks,
                'both_pass': results.both_pass,
                'both_fail': results.both_fail,
                'pynguin_fail_slm_pass': results.pynguin_fail_slm_pass,
                'pynguin_pass_slm_fail': results.pynguin_pass_slm_fail,
                'supports_hypothesis': results.supports_hypothesis,
                'counter_examples': results.counter_examples,
                'both_meaningful': results.both_meaningful,
                'both_trivial': results.both_trivial,
                'support_ratio': results.support_ratio,
                'tasks_supporting': results.tasks_supporting,
                'tasks_counter': results.tasks_counter,
            },
            'supporting_examples': results.supporting_examples[:10],
            'counter_examples': results.counter_examples_list[:10],
        }, f, indent=2, ensure_ascii=False)

    # Save summary
    summary_output = output_dir / f'assertion_quality_summary.txt'
    with open(summary_output, 'w', encoding='utf-8') as f:
        f.write(summary)

    print()
    print(f"Results saved to: {json_output}")
    print(f"Summary saved to: {summary_output}")


if __name__ == "__main__":
    main()
