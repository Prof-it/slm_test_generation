"""
Assertion Quality Analysis: Pynguin vs SLM Test Comparison

This module provides tools to analyze and compare the quality of test assertions
generated by Pynguin (search-based test generation) versus Small Language Models (SLMs).

Algorithm:
Load benchmark artifacts
Match Pynguin & SLM outputs per task
Extract test code
Extract assertions
Classify assertion quality
Combine with pass/fail signal
Filter to discriminating cases
Aggregate statistics
Generate research report
Export reproducible artifacts

The analysis tests the hypothesis that:
    "Pynguin tests may pass with trivial assertions that don't verify algorithm
     correctness, while SLM tests may fail but contain meaningful assertions
     that test actual algorithm behavior."

Methodology:
    - Classification is based on assertion CONTENT, not variable naming conventions
    - Same classification rules are applied to both Pynguin and SLM
    - Multi-line assertions are properly extracted and analyzed
    - Results are aggregated at both comparison and task levels

Usage:
    python analyze_assertion_quality.py [--output-dir OUTPUT_DIR]
"""

